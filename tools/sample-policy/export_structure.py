#!/usr/bin/env python3
"""Writes omni_browse/src/lib/policy-structure.ts from the sample policy HTML so the proposed policy the
app generates reuses the sample's static clauses word for word.

    python3 tools/sample-policy/build.py && python3 tools/sample-policy/export_structure.py
"""
import html
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "omni_browse/src/lib/policy-structure.ts"
h = (HERE / "sample-policy.html").read_text()


def section(start):
    i = h.index(start)
    return h[i : h.index("</section>", i)]


def clean(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s)).strip()


def pairs(seg):
    return [(clean(a), clean(b)) for a, b in re.findall(r"<h3>(.*?)</h3><p>(.*?)</p>", seg, re.S)]


terms1 = pairs(section("<h2>Terms and conditions (1 of 2)</h2>"))
terms2 = pairs(section("<h2>Terms and conditions (2 of 2)</h2>"))
prem = section("<h2>Premium</h2>")
paras = [clean(p) for p in re.findall(r"<p>(.*?)</p>", prem, re.S)]
gst, ci_note = paras[0], paras[3]
ben = dict(pairs(prem))
death = ben["Death benefit"].replace("1.5 crore rupees", "{sumAssured}")
terms2 = [(t, x.replace("limits stated on page 2", "limits stated in the Benefits section")) for t, x in terms2]
grievance = [clean(x) for x in re.findall(r"<li>(.*?)</li>", section("<h2>Grievance redressal</h2>"), re.S)]
declaration = clean(re.search(r"<h2>Declaration</h2>\s*<p>(.*?)</p>", h, re.S).group(1)).replace(" Premium for the first month has been received (demo payment, no money moved).", "")

ts = f"""// GENERATED by tools/sample-policy/export_structure.py from the sample policy: do not edit by hand.
// The proposed policy the app builds for the customer uses these headings, in this order, and the same
// static clause text as the sample policy PDFs; only the numbers and names come from the application.

export const POLICY_HEADINGS = [
  'Policyholder',
  'Proposed policy schedule',
  'Nomination details',
  'Premium',
  'Benefits',
  'Riders',
  'Terms and conditions (1 of 2)',
  'Terms and conditions (2 of 2)',
  'Customer Information Sheet (summary)',
  'Grievance redressal',
  'Declaration',
] as const;

export const TERMS_1: Array<[string, string]> = {json.dumps(terms1, ensure_ascii=False, indent=2)};

export const TERMS_2: Array<[string, string]> = {json.dumps(terms2, ensure_ascii=False, indent=2)};

export const GST_NOTE = {json.dumps(gst, ensure_ascii=False)};

/** '{{sumAssured}}' is replaced with the customer's sum assured label. */
export const DEATH_BENEFIT = {json.dumps(death, ensure_ascii=False)};

export const NO_MATURITY_BENEFIT = {json.dumps(ben["No maturity benefit"], ensure_ascii=False)};

export const CI_RIDER_NOTE = {json.dumps(ci_note, ensure_ascii=False)};

export const GRIEVANCE_LADDER: string[] = {json.dumps(grievance, ensure_ascii=False, indent=2)};

export const DECLARATION_TEXT = {json.dumps(declaration, ensure_ascii=False)};

export const RIDER_CATALOG = [
  {{ key: 'criticalIllness', name: 'Critical illness', pays: 'Lump sum of 10 lakh, 25 lakh or 50 lakh rupees on diagnosis of a covered critical illness', price: 'Rs 89 / Rs 149 / Rs 269' }},
  {{ key: 'accidentalDeath', name: 'Accidental death and disability', pays: '50 lakh rupees lump sum, or 1 lakh rupees a month for 100 months', price: 'Rs 79 / Rs 129' }},
  {{ key: 'waiverOfPremium', name: 'Waiver of premium', pays: 'Future premiums waived on a covered permanent disability', price: 'Rs 42' }},
  {{ key: 'hospitalCash', name: 'Hospital daily cash', pays: '2,000 rupees for each day of hospitalisation', price: 'Rs 55' }},
] as const;
"""
OUT.write_text(ts)
print("wrote", OUT, len(terms1), len(terms2), len(grievance))
